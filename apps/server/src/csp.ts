import { randomBytes } from 'node:crypto';
import type { FastifyRequest } from 'fastify';

/**
 * Nonce-based `script-src` for the two HTML surfaces (10-security §7.1 follow-up).
 *
 * WHY THIS MATTERS MORE THAN IT LOOKS: the SPA deliberately keeps the access token in memory only,
 * never in localStorage. That defends against a *stolen device* reading storage; it does nothing
 * against injected script, which can simply call `GET /auth/session` with the browser's own httpOnly
 * cookie and be handed a fresh bearer token. `script-src` is the control that actually closes that
 * path, so it is the one real mitigation for XSS here — not a hardening nicety.
 *
 * Why a nonce and not `'self'` alone: the landing page (ADR-019j) carries two large inline scripts
 * that must not be rewritten, and inline script is exactly what `'unsafe-inline'` would re-permit for
 * an attacker too. A per-response nonce lets OUR inline scripts run while an injected one — which
 * cannot guess the nonce — does not.
 *
 * `'self'` is kept alongside the nonce because ES module imports do NOT inherit their importer's
 * nonce: `gr-scene.js` imports `./vendor/three.module.min.js`, and dropping `'self'` would black-hole
 * the WebGL scene. Same-origin script is the trust boundary we already have — there is no upload or
 * user-content surface on this origin for an attacker to plant a file behind.
 */

/** Per-response nonce. 16 bytes of CSPRNG — CSP requires ≥128 bits of entropy, base64-encoded. */
export function makeNonce(): string {
  return randomBytes(16).toString('base64');
}

/**
 * The CSP for an HTML document.
 *
 * Third-party origins are enumerated rather than wildcarded, and each one is a deliberate cost:
 *   - fonts.googleapis.com / fonts.gstatic.com — the landing's webfonts. Style and font only; neither
 *     origin can ship script under this policy.
 * `img-src data:` covers the SPA's inline SVG favicon. `object-src 'none'` kills the plugin surface
 * (Flash-era `<object>` payloads still bypass script-src on old engines). `base-uri 'none'` stops an
 * injected `<base>` from re-pointing every relative script URL at an attacker's host.
 *
 * @param nonce value emitted by {@link makeNonce}, already embedded in the document's script tags.
 */
export function htmlCsp(nonce: string): string {
  return [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}'`,
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
    // 'self' is NOT redundant with default-src here: naming font-src at all replaces the fallback,
    // and the SPA self-hosts its woff2 files. Verified in a browser — omitting it blocked all three.
    "font-src 'self' https://fonts.gstatic.com",
    "img-src 'self' data:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "frame-ancestors 'none'",
    "form-action 'self'",
  ].join('; ');
}

/**
 * Stamps `nonce="…"` onto every `<script` tag in a document.
 *
 * Rewriting at serve time rather than committing a `__NONCE__` placeholder into the HTML is
 * deliberate: the SPA's script tags are GENERATED by Vite with hashed filenames, so there is no
 * authored tag to place a placeholder on, and a build that silently stopped substituting would fail
 * open (page works, CSP silently absent) instead of loud.
 *
 * The lookahead requires a delimiter after the tag name so `<scriptsomething` is never matched.
 */
export function injectNonce(html: string, nonce: string): string {
  return html.replace(/<script(?=[\s>])/gi, `<script nonce="${nonce}"`);
}

/** Set by the HTML routes in static.ts; read by the security-headers hook to build the CSP. */
export interface WithNonce {
  cspNonce?: string;
}

export function getNonce(request: FastifyRequest): string | undefined {
  return (request as FastifyRequest & WithNonce).cspNonce;
}

export function setNonce(request: FastifyRequest, nonce: string): void {
  (request as FastifyRequest & WithNonce).cspNonce = nonce;
}
